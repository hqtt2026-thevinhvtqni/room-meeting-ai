"""SQLite-backed resumable upload sessions for the isolated Cloud Drive pilot.

This module is a prototype service component, not an authentication boundary.
The caller must authorize the principal for the supplied scope before every call.
"""
from __future__ import annotations

import hashlib
import os
import re
import secrets
import sqlite3
import tempfile
import time
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from ..storage.protocol import ObjectRef, StorageAdapter, StoredObject
from .lifecycle import migrate_upload_sessions, transition_session, finalize_completion
from ..service.quota_manager import QuotaManager

_SCOPE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,79}$")
_SHA256_RE = re.compile(r"^[a-f0-9]{64}$")


class UploadError(Exception):
    pass


class UploadNotFound(UploadError):
    pass


class UploadConflict(UploadError):
    pass


class UploadLimitExceeded(UploadError):
    pass


class UploadIntegrityError(UploadError):
    pass


@dataclass(frozen=True)
class UploadSession:
    session_id: str
    scope_id: str
    expected_size: int
    expected_sha256: str | None
    status: str
    expires_at: int


class UploadSessionManager:
    """Persists upload metadata and parts; stores final bytes via StorageAdapter.

    Part files live under a dedicated staging directory. Session IDs are random,
    and all path components used for staging are generated by this module.
    """

    def __init__(
        self,
        *,
        database: str | Path,
        staging_root: str | Path,
        storage: StorageAdapter,
        max_object_bytes: int = 512 * 1024 * 1024,
        max_part_bytes: int = 8 * 1024 * 1024,
        ttl_seconds: int = 24 * 60 * 60,
        quota_manager: QuotaManager | None = None,
    ):
        if min(max_object_bytes, max_part_bytes, ttl_seconds) <= 0:
            raise ValueError("limits and TTL must be positive")
        self.database = Path(database)
        self.database.parent.mkdir(parents=True, exist_ok=True)
        self.staging_root = Path(staging_root)
        if self.staging_root.exists() and self.staging_root.is_symlink():
            raise UploadError("staging root must not be a symlink")
        self.staging_root.mkdir(parents=True, exist_ok=True)
        self.staging_root = self.staging_root.resolve(strict=True)
        if not self.staging_root.is_dir():
            raise UploadError("staging root must be a directory")
        self.storage = storage
        self.quota_manager = quota_manager
        if quota_manager is not None and Path(quota_manager.database).resolve() != self.database.resolve():
            raise UploadError("quota and upload metadata must share one SQLite database for atomic pilot accounting")
        self.max_object_bytes = max_object_bytes
        self.max_part_bytes = max_part_bytes
        self.ttl_seconds = ttl_seconds
        self._initialize()

    def _connect(self) -> sqlite3.Connection:
        conn = sqlite3.connect(self.database, timeout=15)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys=ON")
        conn.execute("PRAGMA journal_mode=WAL")
        return conn

    def _initialize(self) -> None:
        with self._connect() as conn:
            conn.executescript("""
                CREATE TABLE IF NOT EXISTS upload_sessions (
                    session_id TEXT PRIMARY KEY,
                    scope_id TEXT NOT NULL,
                    object_key TEXT NOT NULL UNIQUE,
                    expected_size INTEGER NOT NULL,
                    expected_sha256 TEXT,
                    max_bytes INTEGER NOT NULL,
                    status TEXT NOT NULL,
                    created_at INTEGER NOT NULL,
                    expires_at INTEGER NOT NULL,
                    completed_sha256 TEXT,
                    completed_size INTEGER,
                    quota_reservation_id TEXT
                );
                CREATE TABLE IF NOT EXISTS upload_parts (
                    session_id TEXT NOT NULL REFERENCES upload_sessions(session_id),
                    part_number INTEGER NOT NULL,
                    size_bytes INTEGER NOT NULL,
                    sha256 TEXT NOT NULL,
                    PRIMARY KEY(session_id, part_number)
                );
            """)
            columns = {r["name"] for r in conn.execute("PRAGMA table_info(upload_sessions)")}
            if "quota_reservation_id" not in columns:
                conn.execute("ALTER TABLE upload_sessions ADD COLUMN quota_reservation_id TEXT")
            migrate_upload_sessions(conn)
            if self.quota_manager is not None:
                self.quota_manager.ensure_schema(conn)

    @staticmethod
    def _validate_scope(scope_id: str) -> None:
        if not isinstance(scope_id, str) or not _SCOPE_RE.fullmatch(scope_id):
            raise UploadError("invalid scope identifier")

    def _session_dir(self, session_id: str) -> Path:
        if not re.fullmatch(r"[A-Za-z0-9_-]{32,64}", session_id):
            raise UploadNotFound("upload session not found")
        path = self.staging_root / session_id
        resolved = path.resolve()
        if resolved.parent != self.staging_root:
            raise UploadNotFound("upload session not found")
        return path

    def begin_upload(
        self,
        *,
        scope_id: str,
        expected_size: int,
        expected_sha256: str | None = None,
    ) -> UploadSession:
        self._validate_scope(scope_id)
        if expected_size < 0 or expected_size > self.max_object_bytes:
            raise UploadLimitExceeded("object size is outside configured limits")
        if expected_sha256 is not None and not _SHA256_RE.fullmatch(expected_sha256):
            raise UploadError("expected_sha256 must be a lowercase SHA-256 hex digest")
        now = int(time.time())
        session_id = secrets.token_urlsafe(32)
        # Opaque key generated by the service; never accept a filesystem path from a caller.
        object_key = f"{scope_id}/{uuid.uuid4().hex}"
        expires_at = now + self.ttl_seconds
        # Persist CREATED first. A crash from this point is detectable and never
        # mistaken for an upload-ready session.
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            reservation_id = None
            if self.quota_manager is not None and expected_size > 0:
                reservation_id = self.quota_manager.reserve_in_transaction(conn, scope_id, expected_size)
            conn.execute(
                """INSERT INTO upload_sessions
                   (session_id, scope_id, object_key, expected_size, expected_sha256,
                    max_bytes, status, created_at, expires_at, quota_reservation_id)
                   VALUES (?, ?, ?, ?, ?, ?, 'CREATED', ?, ?, ?)""",
                (session_id, scope_id, object_key, expected_size, expected_sha256,
                 self.max_object_bytes, now, expires_at, reservation_id),
            )
        try:
            session_dir = self._session_dir(session_id)
            session_dir.mkdir(mode=0o700)
            if session_dir.is_symlink() or not session_dir.is_dir():
                raise UploadError("staging session path is not a real directory")
            # Make the directory entry durable where the platform supports it.
            try:
                dir_fd = os.open(self.staging_root, os.O_RDONLY)
                try:
                    os.fsync(dir_fd)
                finally:
                    os.close(dir_fd)
            except OSError:
                # Directory fsync is not available on every supported platform.
                pass
            with self._connect() as conn:
                conn.execute("BEGIN IMMEDIATE")
                transition_session(
                    conn, session_id=session_id, expected_state="CREATED",
                    new_state="UPLOADING",
                )
        except Exception as exc:
            # Leave a durable recovery marker. Do not silently delete the row or
            # staging data: a later read-only reconciler must inspect both.
            try:
                with self._connect() as conn:
                    conn.execute("BEGIN IMMEDIATE")
                    transition_session(
                        conn, session_id=session_id, expected_state="CREATED",
                        new_state="RECOVERY_REQUIRED", error_code="STAGING_INIT_FAILED",
                    )
            except Exception:
                pass
            raise UploadError("upload session requires staging recovery") from exc
        return UploadSession(session_id, scope_id, expected_size, expected_sha256, "UPLOADING", expires_at)

    def _load_open(self, conn: sqlite3.Connection, session_id: str, scope_id: str) -> sqlite3.Row:
        self._validate_scope(scope_id)
        row = conn.execute(
            "SELECT * FROM upload_sessions WHERE session_id=? AND scope_id=?",
            (session_id, scope_id),
        ).fetchone()
        if row is None:
            raise UploadNotFound("upload session not found")
        if row["status"] not in {"OPEN", "UPLOADING"}:
            raise UploadConflict("upload session is not open")
        if row["expires_at"] < int(time.time()):
            raise UploadConflict("upload session has expired")
        return row

    def put_part(
        self,
        *,
        session_id: str,
        scope_id: str,
        part_number: int,
        source: BinaryIO,
    ) -> dict[str, int | str]:
        if not isinstance(part_number, int) or part_number < 1 or part_number > 10000:
            raise UploadError("part_number must be between 1 and 10000")
        with self._connect() as conn:
            row = self._load_open(conn, session_id, scope_id)
        session_dir = self._session_dir(session_id)
        digest = hashlib.sha256()
        total = 0
        fd, temp_name = tempfile.mkstemp(prefix=".part-", dir=str(session_dir))
        try:
            with os.fdopen(fd, "wb") as output:
                while True:
                    chunk = source.read(min(1024 * 1024, self.max_part_bytes + 1))
                    if not chunk:
                        break
                    total += len(chunk)
                    if total > self.max_part_bytes:
                        raise UploadLimitExceeded("part exceeds configured maximum")
                    digest.update(chunk)
                    output.write(chunk)
                output.flush()
                os.fsync(output.fileno())
            part_hash = digest.hexdigest()
            final_path = session_dir / f"part-{part_number:05d}.bin"
            with self._connect() as conn:
                conn.execute("BEGIN IMMEDIATE")
                current = self._load_open(conn, session_id, scope_id)
                existing = conn.execute(
                    "SELECT size_bytes, sha256 FROM upload_parts WHERE session_id=? AND part_number=?",
                    (session_id, part_number),
                ).fetchone()
                if existing:
                    if existing["size_bytes"] == total and existing["sha256"] == part_hash:
                        final_path = session_dir / f"part-{part_number:05d}.bin"
                        if not final_path.is_file() or final_path.is_symlink():
                            raise UploadIntegrityError("part metadata exists but staged file is missing or unsafe")
                        on_disk_hash = hashlib.sha256()
                        on_disk_size = 0
                        with final_path.open("rb") as saved:
                            while True:
                                chunk = saved.read(1024 * 1024)
                                if not chunk:
                                    break
                                on_disk_size += len(chunk)
                                on_disk_hash.update(chunk)
                        if on_disk_size != total or on_disk_hash.hexdigest() != part_hash:
                            raise UploadIntegrityError("existing staged part does not match its metadata")
                        os.unlink(temp_name)
                        return {"part_number": part_number, "size_bytes": total, "sha256": part_hash}
                    raise UploadConflict("part number already exists with different content")

                final_path = session_dir / f"part-{part_number:05d}.bin"
                if final_path.exists() or final_path.is_symlink():
                    if final_path.is_symlink() or not final_path.is_file():
                        raise UploadIntegrityError("orphan staged part path is not a regular file")
                    # Recover a crash after atomic rename but before metadata commit.
                    on_disk_hash = hashlib.sha256()
                    on_disk_size = 0
                    with final_path.open("rb") as saved:
                        while True:
                            chunk = saved.read(1024 * 1024)
                            if not chunk:
                                break
                            on_disk_size += len(chunk)
                            on_disk_hash.update(chunk)
                    if on_disk_size != total or on_disk_hash.hexdigest() != part_hash:
                        raise UploadConflict("orphan staged part exists with different content; manual recovery required")
                    os.unlink(temp_name)
                else:
                    os.replace(temp_name, final_path)
                    # Persist the directory entry when the platform supports it.
                    try:
                        dir_fd = os.open(session_dir, os.O_RDONLY)
                        try:
                            os.fsync(dir_fd)
                        finally:
                            os.close(dir_fd)
                    except OSError:
                        pass
                conn.execute(
                    "INSERT INTO upload_parts(session_id, part_number, size_bytes, sha256) VALUES (?, ?, ?, ?)",
                    (session_id, part_number, total, part_hash),
                )
            return {"part_number": part_number, "size_bytes": total, "sha256": part_hash}
        except Exception:
            try:
                os.unlink(temp_name)
            except FileNotFoundError:
                pass
            raise

    def list_parts(self, *, session_id: str, scope_id: str) -> list[dict[str, int | str]]:
        with self._connect() as conn:
            self._load_open(conn, session_id, scope_id)
            rows = conn.execute(
                "SELECT part_number, size_bytes, sha256 FROM upload_parts WHERE session_id=? ORDER BY part_number",
                (session_id,),
            ).fetchall()
        return [dict(row) for row in rows]

    def complete_upload(self, *, session_id: str, scope_id: str) -> StoredObject:
        # Claim the session before reading parts so no new part can race with assembly.
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            row = self._load_open(conn, session_id, scope_id)
            transition_session(
                conn, session_id=session_id, expected_state="UPLOADING",
                new_state="VERIFYING",
            )
            parts = conn.execute(
                "SELECT part_number, size_bytes, sha256 FROM upload_parts WHERE session_id=? ORDER BY part_number",
                (session_id,),
            ).fetchall()

        assembled_name = None
        fd = None
        digest = hashlib.sha256()
        state_for_error = "VERIFYING"
        try:
            session_dir = self._session_dir(session_id)
            fd, assembled_name = tempfile.mkstemp(prefix=".assembled-", dir=str(self.staging_root))
            if not parts:
                raise UploadConflict("upload has no parts")
            expected_numbers = list(range(1, len(parts) + 1))
            actual_numbers = [part["part_number"] for part in parts]
            if actual_numbers != expected_numbers:
                raise UploadConflict("upload parts are not contiguous from 1")
            total = sum(part["size_bytes"] for part in parts)
            if total != row["expected_size"]:
                raise UploadIntegrityError("assembled size does not match expected size")

            with os.fdopen(fd, "wb") as assembled:
                fd = None
                for part in parts:
                    part_path = session_dir / f"part-{part['part_number']:05d}.bin"
                    if part_path.is_symlink() or not part_path.is_file():
                        raise UploadIntegrityError("staged part is missing or unsafe")
                    part_digest = hashlib.sha256()
                    part_size = 0
                    with part_path.open("rb") as source:
                        while True:
                            chunk = source.read(1024 * 1024)
                            if not chunk:
                                break
                            part_size += len(chunk)
                            part_digest.update(chunk)
                            digest.update(chunk)
                            assembled.write(chunk)
                    if part_size != part["size_bytes"] or part_digest.hexdigest() != part["sha256"]:
                        raise UploadIntegrityError("staged part failed size/SHA-256 verification")
                assembled.flush()
                os.fsync(assembled.fileno())

            actual_hash = digest.hexdigest()
            if row["expected_sha256"] and actual_hash != row["expected_sha256"]:
                raise UploadIntegrityError("assembled SHA-256 does not match expected digest")

            # Durable state boundary before calling the provider. A crash after
            # this point is visible as COMMITTING and is never reported complete.
            with self._connect() as conn:
                conn.execute("BEGIN IMMEDIATE")
                # Persist computed content commitment atomically with COMMITTING.
                conn.execute(
                    "UPDATE upload_sessions SET commit_sha256=?, commit_size=?, "
                    "commit_manifest_version=1 WHERE session_id=? AND status='VERIFYING'",
                    (actual_hash, total, session_id),
                )
                transition_session(
                    conn, session_id=session_id, expected_state="VERIFYING",
                    new_state="COMMITTING",
                )
            state_for_error = "COMMITTING"

            with open(assembled_name, "rb") as source:
                stored = self.storage.put_stream(
                    row["object_key"], source, max_bytes=row["max_bytes"]
                )
            if stored.size_bytes != total or stored.sha256 != actual_hash:
                raise UploadIntegrityError("storage adapter integrity result mismatch")

            # Verify the provider's persisted object, not just the upload response.
            confirmed = self.storage.head(stored.ref)
            if confirmed.size_bytes != total or confirmed.sha256 != actual_hash:
                raise UploadIntegrityError("stored object HEAD verification mismatch")

            with self._connect() as conn:
                conn.execute("BEGIN IMMEDIATE")
                state_row = conn.execute(
                    "SELECT state_version FROM upload_sessions WHERE session_id=? AND status='COMMITTING'",
                    (session_id,),
                ).fetchone()
                if state_row is None:
                    raise UploadConflict("session left COMMITTING; storage outcome requires reconciliation")
                finalize_completion(
                    conn, session_id=session_id, expected_version=state_row["state_version"],
                    completed_sha256=actual_hash, completed_size=total,
                )
                reservation_id = conn.execute("SELECT quota_reservation_id FROM upload_sessions WHERE session_id=?",
                                               (session_id,)).fetchone()["quota_reservation_id"]
                if self.quota_manager is not None and reservation_id is not None:
                    self.quota_manager.commit_in_transaction(conn, reservation_id, actual_bytes=total)
            return stored
        except Exception as exc:
            # Preserve ambiguity for a reconciler. Never claim completion or
            # silently reopen a session after provider-side work may have begun.
            target_state = "RECOVERY_REQUIRED"
            try:
                with self._connect() as conn:
                    conn.execute("BEGIN IMMEDIATE")
                    transition_session(
                        conn, session_id=session_id, expected_state=state_for_error,
                        new_state=target_state, error_code=type(exc).__name__.upper()[:64],
                    )
            except Exception:
                # A concurrent transition or process-level DB failure is itself
                # evidence for reconciliation; retain the current durable state.
                pass
            raise
        finally:
            if fd is not None:
                try:
                    os.close(fd)
                except OSError:
                    pass
            if assembled_name is not None:
                try:
                    os.unlink(assembled_name)
                except FileNotFoundError:
                    pass

    def abort_upload(self, *, session_id: str, scope_id: str) -> None:
        self._validate_scope(scope_id)
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute(
                "SELECT status FROM upload_sessions WHERE session_id=? AND scope_id=?",
                (session_id, scope_id),
            ).fetchone()
            if row is None:
                raise UploadNotFound("upload session not found")
            if row["status"] == "ABORTED":
                return
            if row["status"] not in {"OPEN", "UPLOADING", "CREATED"}:
                raise UploadConflict("only an uncommitted upload can be aborted")
            expected = "UPLOADING" if row["status"] == "OPEN" else row["status"]
            transition_session(
                conn, session_id=session_id, expected_state=expected,
                new_state="ABORTED", error_code="USER_ABORT",
            )
            reservation_id = conn.execute("SELECT quota_reservation_id FROM upload_sessions WHERE session_id=?",
                                           (session_id,)).fetchone()["quota_reservation_id"]
            if self.quota_manager is not None and reservation_id is not None:
                self.quota_manager.release_in_transaction(conn, reservation_id)
        # Deliberately retain staging bytes. Immediate deletion can race with a
        # part writer that is still streaming to a temporary file. A separate,
        # age-gated cleanup worker must inspect and remove aborted data later.
