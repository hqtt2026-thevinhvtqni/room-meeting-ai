"""Coder Agent backend (charter §3, Vi role).

Deterministic artifact generator for the vertical slice (D-03 in
DECISION_REGISTER): the intelligence of the Coder is swappable. The
protocol contract — receive brief/feedback, emit a versioned, hashed
artifact — is what Work 51 verifies.

The Coder NEVER sees acceptance programs (opacity rule) and NEVER
self-approves its artifact (charter: "Coder không được tự phê duyệt").
"""

from __future__ import annotations

from .a2a import AgentBackend, artifact_text, make_task, make_text_artifact
from .evidence import sha256_text
import textwrap

ARTIFACT_TEMPLATE = '''"""Artifact {artifact_filename} for contract {contract_id}.

Generated by Coder Agent (a2a_ct coder_agent) — artifact version {version}.
Objective: {objective}
"""


{signature}:
{body}
'''


def build_artifact_text(contract_id: str, objective: str, signature: str,
                        body: str, version: int, artifact_filename: str) -> str:
    return ARTIFACT_TEMPLATE.format(
        contract_id=contract_id,
        objective=objective,
        signature=signature,
        body=textwrap.indent(body.strip(), "    "),
        version=version,
        artifact_filename=artifact_filename,
    )


class CoderBackend(AgentBackend):
    """State per task id: {"contract_id", "mode", "version", "round"}."""

    def agent_card(self) -> dict:
        return {
            "protocolVersion": "1.0",
            "version": "1.2.0",
            "preferredTransport": "JSONRPC",
            "name": "work51-coder-agent",
            "description": "Produces versioned artifact per Work Contract brief/feedback.",
            "url": "in-process://work51/coder",
            "capabilities": {"pushNotifications": False, "streaming": False},
            "defaultInputModes": ["application/json"],
            "defaultOutputModes": ["application/json", "text/plain"],
            "skills": [{"id": "work51-coder", "name": "Artifact generation", "description": "Generates a versioned code artifact from a Work Contract brief and feedback.", "tags": ["coding", "artifact-generation"], "examples": ["Generate a Python artifact from a brief."]}],
            "metadata": {"role": "coder", "self_approval": False},
        }

    # ------------------------------------------------------------------

    def _state(self, task: dict) -> dict:
        return task.get("metadata", {}).get("coder", {})


    def handle_task(self, task_id: str, payload: dict, existing: dict | None) -> dict:
        kind = payload.get("kind")
        if kind == "brief":
            if existing is not None and self._state(existing).get("contract_id"):
                # Idempotent replay: same task id + brief -> same artifact, no re-roll.
                return existing
            return self._emit(task_id, payload, version=1, round_=0)
        if kind == "feedback":
            if existing is None:
                return make_task(
                    task_id, "failed",
                    status_message="feedback for unknown task",
                    metadata={"error": "no_brief_for_feedback"},
                )
            prev = self._state(existing)
            version = int(prev.get("version", 1)) + 1
            round_ = int(prev.get("round", 0)) + 1
            return self._emit(task_id, payload, version=version, round_=round_)
        return make_task(
            task_id, "failed",
            status_message=f"unsupported payload kind: {kind!r}",
            metadata={"error": "unsupported_kind"},
        )

    # ------------------------------------------------------------------

    def _emit(self, task_id: str, payload: dict, version: int, round_: int) -> dict:
        contract_id = payload.get("contract_id", "")
        signature = payload.get("function_signature", "")
        objective = payload.get("objective", "")
        filename = payload.get("artifact_filename", "artifact.py")
        bodies = payload.get("solution_bodies", {})
        mode = payload.get("coder_mode", "correct")

        if round_ == 0:
            # First emission: honor the requested mode.
            body = bodies["buggy"] if mode in ("seeded_bug", "always_bug") else bodies["correct"]
        else:
            # On feedback: seeded_bug fixes itself; always_bug never does.
            body = bodies["buggy"] if mode == "always_bug" else bodies["correct"]

        text = build_artifact_text(contract_id, objective, signature, body, version, filename)
        artifact = make_text_artifact(
            name=filename,
            text=text,
            sha256=sha256_text(text),
            version=version,
            description=f"coder artifact v{version} for {contract_id}",
        )
        return make_task(
            task_id,
            "completed",
            artifacts=[artifact],
            status_message=f"artifact v{version} emitted",
            metadata={
                "coder": {
                    "contract_id": contract_id,
                    "mode": mode,
                    "version": version,
                    "round": round_,
                }
            },
        )
